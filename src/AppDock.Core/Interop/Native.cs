[StructLayout(LayoutKind.Sequential)]
internal struct RECT
{
    public int Left;
    public int Top;
    public int Right;
    public int Bottom;

    public RECT(Rect r)
    {
        Left = r.Left;
        Top = r.Top;
        Right = r.Right;
        Bottom = r.Bottom;
    }

    public readonly Rect ToRect() => new(Left, Top, Right, Bottom);
}

[StructLayout(LayoutKind.Sequential)]
